import java.util.Properties
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    id("rust")
}

val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

val rawVersionName = tauriProperties.getProperty("tauri.android.versionName", "0.1.3")
val computedVersionCode = run {
    val parts = rawVersionName.split(".").mapNotNull { it.toIntOrNull() }
    if (parts.size >= 3) {
        parts[0] * 10000 + parts[1] * 100 + parts[2]
    } else {
        tauriProperties.getProperty("tauri.android.versionCode", "1").toInt()
    }
}

val tauriConfigFile = file("src/main/assets/tauri.conf.json")
val (resolvedAppId, resolvedAppName) = if (tauriConfigFile.exists()) {
    val text = tauriConfigFile.readText()
    val idMatch = Regex(""""identifier"\s*:\s*"([^"]+)"""").find(text)
    val nameMatch = Regex(""""productName"\s*:\s*"([^"]+)"""").find(text)
    Pair(
        project.findProperty("topaAppId")?.toString() ?: idMatch?.groupValues?.get(1) ?: "io.github.kaualimadesouza.topa",
        project.findProperty("topaAppName")?.toString() ?: nameMatch?.groupValues?.get(1) ?: "TOPA",
    )
} else {
    Pair(
        project.findProperty("topaAppId")?.toString() ?: System.getenv("TOPA_APP_ID") ?: "io.github.kaualimadesouza.topa",
        project.findProperty("topaAppName")?.toString() ?: System.getenv("TOPA_APP_NAME") ?: "TOPA",
    )
}

val isLoja = resolvedAppId.endsWith(".loja")

android {
    compileSdk = 37
    namespace = resolvedAppId
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        manifestPlaceholders["appName"] = resolvedAppName
        applicationId = resolvedAppId
        minSdk = 24
        targetSdk = 37
        versionCode = computedVersionCode
        versionName = rawVersionName
    }
    sourceSets {
        getByName("main") {
            if (isLoja) {
                manifest.srcFile("src/loja/AndroidManifest.xml")
                res.srcDirs("src/loja/res", "src/main/res")
                java.srcDirs("src/loja/java", "src/main/java")
            } else {
                manifest.srcFile("src/cliente/AndroidManifest.xml")
                res.srcDirs("src/cliente/res", "src/main/res")
                java.srcDirs("src/cliente/java", "src/main/java")
            }
        }
    }
    buildTypes {
        getByName("debug") {
            applicationIdSuffix = ".debug"
            manifestPlaceholders["usesCleartextTraffic"] = "true"
            isDebuggable = true
            isJniDebuggable = true
            isMinifyEnabled = false
            packaging {
                jniLibs.keepDebugSymbols.add("*/arm64-v8a/*.so")
                jniLibs.keepDebugSymbols.add("*/armeabi-v7a/*.so")
                jniLibs.keepDebugSymbols.add("*/x86/*.so")
                jniLibs.keepDebugSymbols.add("*/x86_64/*.so")
            }
        }
        getByName("release") {
            optimization {
               enable = true
            }
            proguardFiles(
                *fileTree(".") {
                  include("**/*.pro")
                  exclude("build/**")
                }.files.toTypedArray()
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_1_8
        targetCompatibility = JavaVersion.VERSION_1_8
    }
    buildFeatures {
        buildConfig = true
    }
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_1_8
    }
}

rust {
    rootDirRel = "../../../"
}

dependencies {
    implementation("androidx.webkit:webkit:1.14.0")
    implementation("androidx.appcompat:appcompat:1.7.1")
    implementation("androidx.activity:activity-ktx:1.10.1")
    implementation("com.google.android.material:material:1.12.0")
    implementation("androidx.lifecycle:lifecycle-process:2.10.0")
    testImplementation("junit:junit:4.13.2")
    androidTestImplementation("androidx.test.ext:junit:1.1.4")
    androidTestImplementation("androidx.test.espresso:espresso-core:3.5.0")
}

val cleanStaleGenerated by tasks.registering(Delete::class) {
    if (isLoja) {
        delete("src/main/java/io/github/kaualimadesouza/topa/generated")
    } else {
        delete("src/main/java/io/github/kaualimadesouza/topa/loja/generated")
    }
}

tasks.named("preBuild") {
    dependsOn(cleanStaleGenerated)
}

apply(from = file("tauri.build.gradle.kts"))
